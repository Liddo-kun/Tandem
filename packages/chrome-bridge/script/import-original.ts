import { createHash } from "node:crypto"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { resolve, join } from "node:path"

// Local extraction only. The installed proprietary plugin retains its notices;
// this importer does not establish permission to redistribute it.
const source = resolve(process.argv[2] ?? "")
if (!process.argv[2]) throw new Error("Supply the original chrome-standalone plugin root")
const destination = resolve(import.meta.dir, "../vendor/original")
const service = await readFile(join(source, "scripts/browser-service.mjs"), "utf8")
const adapter = await readFile(resolve(import.meta.dir, "../src/original-exports.js"), "utf8")
const hash = createHash("sha256").update(service).digest("hex")
const pinned = "3027e8e47d3241f8fde99078a9ced4647ac1732b614b3704628405236f8ac18b"
if (hash !== pinned) throw new Error(`Unsupported original service ${hash}; review adapter symbols before updating the pin`)
await mkdir(destination, { recursive: true })
await writeFile(join(destination, "browser-service.mjs"), service + "\n" + adapter)
await writeFile(join(destination, "browser-service.d.mts"), `// Generated by script/import-original.ts: trusted host seam for the pinned bundle.
export function browserDocumentationSource(): {
  documentation: Record<string, string>
  documentManifest: Array<{ name: string; mode: string; description?: string; requiredFor?: string[] }>
}
export function selectBrowserDocuments(supportedMembers: string[]): {
  guidanceNames: string[]
  lookup: Array<{ name: string; description: string }>
}
export function createBrowserEngine(api: any, browserId: string, info: any, runtime: any, config: any): {
  context: any
  execute(type: string, params: Record<string, unknown>): Promise<any>
  input(params: Record<string, unknown>, action: "fill" | "press"): Promise<any>
  cleanup(tabId: number): Promise<void>
  dispose(): void
}
`)
for (const name of ["browser-client.mjs", "browser-accessibility.wasm.br", "zxing_reader.wasm"])
  await writeFile(join(destination, name), await readFile(join(source, "scripts", name)))
await writeFile(join(destination, "PROVENANCE.md"), await readFile(join(source, "PROVENANCE.md")))
await writeFile(join(destination, "source.json"), JSON.stringify({ source, sha256: hash, adaptation: "src/original-exports.js appended; original service bytes unchanged" }, null, 2) + "\n")
console.log(JSON.stringify({ destination, sha256: hash }))
